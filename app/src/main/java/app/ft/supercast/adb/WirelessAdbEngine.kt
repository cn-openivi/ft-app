package app.ft.supercast.adb

import android.content.Context
import app.ft.supercast.Helper
import io.github.rhythmcache.adb.AdbConnection
import io.github.rhythmcache.adb.FileKeyProvider
import io.github.rhythmcache.adb.pairing.buildPairingIdentity
import io.github.rhythmcache.adb.AdbClient as LibraryAdbClient
import io.github.rhythmcache.adb.runShell
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import kotlinx.coroutines.withTimeout
import java.io.ByteArrayInputStream
import java.io.File
import java.security.MessageDigest
import java.security.cert.CertificateFactory

/**
 * Only the loopback adbd of this very phone may be targeted.
 * A changing service port is a locator, NEVER an authentication secret.
 * No pairing code or secret keys are sent to logs.
 */
internal object WirelessAdbEngine {
    private const val HOST = "127.0.0.1"
    private const val KEY_FILE = "ft_adb_tls.key"
    private const val PEER_SHA = "ft_adb_tls.peer.sha256"
    private fun keyFile(context: Context) = File(context.filesDir, KEY_FILE)
    private fun peerFile(context: Context) = File(context.filesDir, PEER_SHA)
    fun isPaired(context: Context): Boolean =
        keyFile(context).isFile && peerFile(context).readBytesOrEmpty().size == 32

    private fun File.readBytesOrEmpty(): ByteArray = if (isFile) readBytes() else byteArrayOf()

    private fun provider(context: Context) =
        FileKeyProvider(keyFile(context), identityComment = "FT")

    private fun sha256OfPeer(pem: String): ByteArray {
        val certificate = CertificateFactory.getInstance("X.509")
            .generateCertificate(ByteArrayInputStream(pem.toByteArray(Charsets.US_ASCII)))
        return MessageDigest.getInstance("SHA-256").digest(certificate.encoded)
    }

    /** SPAKE2 authenticates this temporary pairing session before persisting peer identity. */
    suspend fun pair(context: Context, pairingPort: Int, code: String): Boolean = withContext(Dispatchers.IO) {
        require(code.length == 6 && code.all(Char::isDigit))
        require(pairingPort in 1..65535)
        val store = provider(context)
        val result = withTimeout(12_000L) {
            LibraryAdbClient.pairTls(HOST, pairingPort, code, store, connectTimeoutMs = 8_000)
        }
        if (result.isFailure) return@withContext false
        val peerPem = result.getOrThrow().peerCertPem ?: return@withContext false
        val fingerprint = sha256OfPeer(peerPem)
        // File is app-private and excluded from Android backup.
        val target = peerFile(context)
        val tmp = File(context.filesDir, PEER_SHA + ".pending")
        tmp.writeBytes(fingerprint)
        tmp.setReadable(false, false)
        tmp.setReadable(true, true)
        if (!tmp.renameTo(target)) {
            tmp.delete()
            return@withContext false
        }
        true
    }

    /** Explicit authenticated TLS transport, rather than plain legacy :5555. */
    suspend fun startHelper(context: Context, connectionPort: Int, token: String): Boolean = withContext(Dispatchers.IO) {
        require(connectionPort in 1..65535)
        val fingerprint = peerFile(context).readBytesOrEmpty()
        if (fingerprint.size != 32) return@withContext false
        val apk = Helper.apkPath(context) ?: return@withContext false
        val keys = provider(context)
        val identity = buildPairingIdentity(keys)
        val transport = PinnedTlsPacketTransport.connect(HOST, connectionPort, identity, fingerprint)
        val connection = try {
            AdbConnection.connect(transport, keys, handshakeTimeoutMs = 8_000, skipInitialCnxn = true)
        } catch (e: Exception) {
            transport.close()
            throw e
        }
        connection.use { conn ->
            // The first command is a bounded shell-v2 test. The helper runs in
            // the phone's shell UID and calls back to SuperCastProvider.
            val probe = withTimeout(8_000L) { conn.runShell("id -u") }
            if (!probe.isSuccess || probe.stdoutText.trim() != "2000") return@withContext false
            // Token is a random hex string generated by SuperCast, never raw user input.
            if (!token.matches(Regex("[a-f0-9]{48}"))) return@withContext false
            val command = "env CLASSPATH=" + shellQuote(apk) + " app_process / " +
                Helper.MAIN + " token=" + token
            val launch = "sh -c " + shellQuote("nohup " + command +
                " >/data/local/tmp/ft-helper.log 2>&1 </dev/null &")
            withTimeout(8_000L) { conn.runShell(launch) }.isSuccess
        }
    }

    private fun shellQuote(raw: String) = "'" + raw.replace("'", "'\\''") + "'"
}
